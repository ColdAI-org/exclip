/** Regenerates src/sodax/tokens.ts, or with --stocks src/sodax/stock-tokens.ts, from a capture of SODAX's swap token
 * list (GET /swaps/tokens).
 * Usage: pnpm --filter @exclip/wallet run gen:tokens <path-to-swaps_tokens.json>
 *        pnpm --filter @exclip/wallet run gen:stock-tokens <path-to-swaps_tokens.json>
 *
 * Keeps the networks the embedded wallet signs on or delivers to (src/sodax/chains.ts) and checks every address.
 * tokens.ts drops real-world assets (isRwa): it is the table every build uses. stock-tokens.ts keeps only them, for a
 * build that switches tokenised stocks on (docs/tokenised-stocks.md). A stock whose symbol is also a coin's, in tokens.ts
 * or the price bands, is left out, so a symbol never means two things; a stock at an address tokens.ts lists as a coin
 * stops the run (regenerate both from one capture). The output is a reviewed file: diff it before committing. */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { getAddress, isAddress } from "viem";
import { EVM_CHAINS, NON_EVM_DESTINATIONS } from "../src/sodax/chains.ts";

type Raw = { symbol: string; name: string; decimals: number; address: string; chainKey: string; hubAsset: string; isRwa?: boolean };
type Rows = Readonly<Record<string, ReadonlyArray<readonly [string, string, number, string]>>>;

const args = process.argv.slice(2);
const stocks = args.includes("--stocks");
const input = args.find((a) => a !== "--stocks");
if (!input) throw new Error("usage: gen:tokens <swaps_tokens.json>, or gen:stock-tokens <swaps_tokens.json>");
const data = JSON.parse(readFileSync(resolve(input), "utf8")) as Record<string, Raw[]>;

// Only for --stocks: the coins already listed, by address on each network and by symbol (case-insensitive).
const coins: Rows = stocks ? (await import("../src/sodax/tokens.ts")).SODAX_TOKENS : {};
const banded = stocks ? Object.keys((await import("../src/sodax/price.ts")).PRICE_BANDS) : [];
const coinSymbols = new Set([...Object.values(coins).flat().map(([, symbol]) => symbol), ...banded].map((s) => s.toUpperCase()));

const SYMBOL = /^[A-Za-z0-9.+_-]{1,16}$/;
const keys = [...Object.keys(EVM_CHAINS), ...Object.keys(NON_EVM_DESTINATIONS)];
const lines: string[] = [];
let count = 0;
for (const key of keys) {
  const list = (data[key] ?? []).filter((t) => (stocks ? t.isRwa === true : !t.isRwa));
  if (!list.length) {
    if (stocks) continue;
    throw new Error(`no tokens for ${key}`);
  }
  lines.push(`  ${JSON.stringify(key)}: [`);
  const seen = new Set<string>();
  for (const t of list) {
    if (t.chainKey !== key) throw new Error(`${t.symbol}: chainKey ${t.chainKey} under ${key}`);
    if (!SYMBOL.test(t.symbol) || !Number.isInteger(t.decimals) || t.decimals < 0 || t.decimals > 36) throw new Error(`bad token ${JSON.stringify(t)}`);
    if (!isAddress(t.hubAsset, { strict: false })) throw new Error(`${key} ${t.symbol}: bad hubAsset`);
    const evm = key in EVM_CHAINS;
    if (evm && !isAddress(t.address, { strict: false })) throw new Error(`${key} ${t.symbol}: bad address`);
    const address = evm ? getAddress(t.address) : t.address;
    const id = evm ? address.toLowerCase() : address;
    if (seen.has(id)) continue;
    seen.add(id);
    if (stocks) {
      if ((coins[key] ?? []).some(([a]) => (evm ? a.toLowerCase() : a) === id)) {
        throw new Error(`${key} ${t.symbol}: tokens.ts lists ${address} as a coin. Regenerate both tables from one capture.`);
      }
      if (coinSymbols.has(t.symbol.toUpperCase())) {
        console.warn(`left out ${key} ${t.symbol}: a coin has that symbol`);
        continue;
      }
    }
    lines.push(`    [${JSON.stringify(address)}, ${JSON.stringify(t.symbol)}, ${t.decimals}, ${JSON.stringify(getAddress(t.hubAsset))}],`);
    count++;
  }
  if (lines.at(-1)!.endsWith(": [")) lines.pop();
  else lines.push("  ],");
}

const out = stocks
  ? `/** GENERATED by scripts/gen-sodax-tokens.ts --stocks from SODAX GET /swaps/tokens. Do not edit by hand; regenerate and review the diff.
 * The tokenised stocks (isRwa) on the wallet's networks, as [address on that network, symbol, decimals, hub (Sonic) asset].
 * ${count} tokens. Only a build with stocks switched on (config.ts STOCKS) reads them, next to tokens.ts. */
export const SODAX_STOCK_TOKENS: Readonly<Record<string, ReadonlyArray<readonly [string, string, number, \`0x\${string}\`]>>> = {
${lines.map((l) => `${l}\n`).join("")}};
`
  : `/** GENERATED by scripts/gen-sodax-tokens.ts from SODAX GET /swaps/tokens. Do not edit by hand; regenerate and review the diff.
 * [address on that network, symbol, decimals, hub (Sonic) asset]. ${count} tokens, real-world assets (isRwa) excluded. */
export const SODAX_TOKENS: Readonly<Record<string, ReadonlyArray<readonly [string, string, number, \`0x\${string}\`]>>> = {
${lines.join("\n")}
};
`;
writeFileSync(resolve(import.meta.dirname, `../src/sodax/${stocks ? "stock-tokens" : "tokens"}.ts`), out);
console.log(`wrote ${count} ${stocks ? "stock " : ""}tokens`);
